import { afterEach, describe, expect, it } from 'bun:test';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { checkCommitMessage } from './check-commit-msg';

const FORMAT_ERROR =
  'commit-msg: the header must follow Conventional Commits, for example "fix(orders): keep the shipment status after a refund". Allowed types: feat, fix, docs, chore, refactor, test, perf, build, ci, style, revert.';

const roots: string[] = [];

afterEach(() => {
  for (const root of roots.splice(0))
    rmSync(root, { recursive: true, force: true });
});

function header(length: number): string {
  const prefix = 'fix: ';
  return prefix + 'a'.repeat(length - prefix.length);
}

describe('checkCommitMessage', () => {
  it.each([
    'feat: add the cart',
    'fix(orders): keep the shipment status',
    'feat!: drop the old API',
    'refactor(api/v2.1)!: rename the handler',
  ])('accepts %s', (message) => {
    expect(checkCommitMessage(message)).toEqual({ ok: true });
  });

  it.each([
    'Merge branch "main" into feature',
    'Revert "feat: add the cart"',
    'fixup! feat: add the cart',
    'squash! feat: add the cart',
    'amend! feat: add the cart',
  ])('exempts %s', (message) => {
    expect(checkCommitMessage(message)).toEqual({ ok: true });
  });

  it('skips comment lines and leading blank lines', () => {
    expect(
      checkCommitMessage('\n\n# a comment\nfix: real header\n\nbody'),
    ).toEqual({ ok: true });
    expect(checkCommitMessage('# only\nnot conventional')).toEqual({
      ok: false,
      error: FORMAT_ERROR,
    });
  });

  it.each([
    'wip: stuff',
    'fix:missing space',
    'fix: ',
    'fix(Orders): uppercase scope',
    'fix(): empty scope',
    'just a sentence',
  ])('rejects %p with the format error', (message) => {
    expect(checkCommitMessage(message)).toEqual({
      ok: false,
      error: FORMAT_ERROR,
    });
  });

  it('rejects an empty message with the format error', () => {
    expect(checkCommitMessage('')).toEqual({ ok: false, error: FORMAT_ERROR });
  });

  it.each([
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'co-authored-by: Jane Doe <jane@example.com>',
    '  Co-authored-by: Someone <a@b.c>',
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    'Generated with Claude Code',
    'Generated by GitHub Copilot',
    'Generated using Claude Code',
    'Co-Authored-By : Claude <noreply@anthropic.com>',
    '- 🤖 drafted by an agent',
    'Assisted-by: Claude',
    'Generated-by: Claude Code',
    'Signed-off-by: Claude <noreply@anthropic.com>',
  ])('rejects the attribution line %p', (line) => {
    expect(
      checkCommitMessage(`fix: keep the status\n\nbody\n\n${line}\n`),
    ).toEqual({
      ok: false,
      error: `commit-msg: remove "${line.trim()}"; commits carry no Co-authored-by or AI attribution lines.`,
    });
  });

  it('rejects attribution on a message with an exempt header', () => {
    expect(
      checkCommitMessage('Merge branch "main"\n\nCo-authored-by: Bot <b@c.d>'),
    ).toEqual({
      ok: false,
      error:
        'commit-msg: remove "Co-authored-by: Bot <b@c.d>"; commits carry no Co-authored-by or AI attribution lines.',
    });
  });

  it('accepts bodies that only mention generated code or co-authors', () => {
    expect(
      checkCommitMessage(
        'fix(types): regenerate\n\nGenerated by supabase gen types.\nThe Co-authored-by rule lives in the hook.',
      ),
    ).toEqual({ ok: true });
  });

  it('accepts a human sign-off and a header that names an AI tool', () => {
    expect(
      checkCommitMessage(
        'feat(ai): call Claude for listing summaries\n\nSigned-off-by: Jane Doe <jane@example.com>',
      ),
    ).toEqual({ ok: true });
  });

  it('rejects attribution in CRLF and tab-indented messages', () => {
    expect(
      checkCommitMessage('fix: a\r\n\r\nCo-authored-by: X <x@y>\r\n').ok,
    ).toBe(false);
    expect(checkCommitMessage('fix: a\n\n\tCO-AUTHORED-BY: X <x@y>').ok).toBe(
      false,
    );
  });

  it('ignores the diff below a CRLF scissors line', () => {
    expect(
      checkCommitMessage(
        'fix: a\r\n# ------------------------ >8 ------------------------\r\n+Co-authored-by: X\r\n',
      ),
    ).toEqual({ ok: true });
  });

  it('ignores comment lines and the diff below the scissors line', () => {
    const message = [
      'fix: keep the status',
      '# Co-authored-by: in a comment',
      '# ------------------------ >8 ------------------------',
      '+Co-authored-by: Claude <noreply@anthropic.com>',
      'Co-authored-by: Claude <noreply@anthropic.com>',
    ].join('\n');
    expect(checkCommitMessage(message)).toEqual({ ok: true });
  });

  it('accepts a 100 character header and rejects 101', () => {
    expect(checkCommitMessage(header(100))).toEqual({ ok: true });
    expect(checkCommitMessage(header(101))).toEqual({
      ok: false,
      error:
        'commit-msg: the header is 101 characters; keep it at 100 or fewer.',
    });
  });
});

describe('check-commit-msg CLI', () => {
  async function run(message: string) {
    const root = mkdtempSync(join(tmpdir(), 'check-commit-msg-'));
    roots.push(root);
    const file = join(root, 'COMMIT_EDITMSG');
    writeFileSync(file, message);
    const proc = Bun.spawn(
      ['bun', join(import.meta.dir, 'check-commit-msg.ts'), file],
      {
        stdout: 'pipe',
        stderr: 'pipe',
      },
    );
    const [stdout, stderr, code] = await Promise.all([
      new Response(proc.stdout).text(),
      new Response(proc.stderr).text(),
      proc.exited,
    ]);
    return { stdout, stderr, code };
  }

  it('exits 0 and prints nothing for a valid header', async () => {
    expect(await run('fix(orders): keep the status\n')).toEqual({
      stdout: '',
      stderr: '',
      code: 0,
    });
  });

  it('exits 1 and prints the error to stderr for an invalid header', async () => {
    expect(await run('did some stuff\n')).toEqual({
      stdout: '',
      stderr: `${FORMAT_ERROR}\n`,
      code: 1,
    });
  });
});

describe('check-commit-msg CLI --range', () => {
  // Hooks export GIT_DIR and friends; drop them so git works on the scratch repo.
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && !key.startsWith('GIT_')) env[key] = value;
  }

  function git(cwd: string, ...args: string[]): string {
    const result = Bun.spawnSync(['git', ...args], { cwd, env });
    if (result.exitCode !== 0) throw new Error(result.stderr.toString());
    return result.stdout.toString().trim();
  }

  function repoWith(messages: string[]): { root: string; shas: string[] } {
    const root = mkdtempSync(join(tmpdir(), 'check-commit-range-'));
    roots.push(root);
    git(root, 'init', '-q');
    git(root, 'config', 'user.name', 'Probe');
    git(root, 'config', 'user.email', 'probe@example.com');
    git(
      root,
      'commit',
      '-q',
      '--allow-empty',
      '--no-verify',
      '-m',
      'chore: base',
    );
    const shas = messages.map((message) => {
      git(root, 'commit', '-q', '--allow-empty', '--no-verify', '-m', message);
      return git(root, 'rev-parse', 'HEAD');
    });
    return { root, shas };
  }

  async function runRange(root: string, range: string) {
    const proc = Bun.spawn(
      ['bun', join(import.meta.dir, 'check-commit-msg.ts'), '--range', range],
      { cwd: root, env, stdout: 'pipe', stderr: 'pipe' },
    );
    const [stdout, stderr, code] = await Promise.all([
      new Response(proc.stdout).text(),
      new Response(proc.stderr).text(),
      proc.exited,
    ]);
    return { stdout, stderr, code };
  }

  it('exits 0 and prints nothing when every commit in the range passes', async () => {
    const { root } = repoWith(['feat: add the cart', 'fix: keep the status']);
    expect(await runRange(root, 'HEAD~2..HEAD')).toEqual({
      stdout: '',
      stderr: '',
      code: 0,
    });
  });

  it('exits 1 and names every failing commit', async () => {
    const { root, shas } = repoWith([
      'did some stuff',
      'feat: fine',
      'fix: keep it\n\nCo-authored-by: Claude <noreply@anthropic.com>',
    ]);
    expect(await runRange(root, 'HEAD~3..HEAD')).toEqual({
      stdout: '',
      stderr: [
        `${shas[0]}: ${FORMAT_ERROR}`,
        `${shas[2]}: commit-msg: remove "Co-authored-by: Claude <noreply@anthropic.com>"; commits carry no Co-authored-by or AI attribution lines.`,
        '',
      ].join('\n'),
      code: 1,
    });
  });

  it('skips commits outside the range', async () => {
    const { root } = repoWith(['did some stuff', 'feat: fine']);
    expect((await runRange(root, 'HEAD~1..HEAD')).code).toBe(0);
  });

  it('rejects attribution hidden below a scissors line in a verbatim commit', async () => {
    const { root } = repoWith([]);
    git(
      root,
      'commit',
      '-q',
      '--allow-empty',
      '--no-verify',
      '--cleanup=verbatim',
      '-m',
      'fix: keep it\n\n# ------------------------ >8 ------------------------\nCo-authored-by: Claude <noreply@anthropic.com>',
    );
    const sha = git(root, 'rev-parse', 'HEAD');
    expect(await runRange(root, 'HEAD~1..HEAD')).toEqual({
      stdout: '',
      stderr: `${sha}: commit-msg: remove "Co-authored-by: Claude <noreply@anthropic.com>"; commits carry no Co-authored-by or AI attribution lines.\n`,
      code: 1,
    });
  });

  it('exits 0 on an empty range', async () => {
    const { root } = repoWith(['did some stuff']);
    expect(await runRange(root, 'HEAD..HEAD')).toEqual({
      stdout: '',
      stderr: '',
      code: 0,
    });
  });

  it('exits 1 when a side of the range is empty', async () => {
    const { root } = repoWith(['did some stuff']);
    expect(await runRange(root, '..HEAD')).toEqual({
      stdout: '',
      stderr: 'commit-msg: --range expects <base>..<head>.\n',
      code: 1,
    });
  });

  it('ignores GIT_DIR from a hook environment', async () => {
    const { root } = repoWith(['did some stuff']);
    const proc = Bun.spawn(
      [
        'bun',
        join(import.meta.dir, 'check-commit-msg.ts'),
        '--range',
        'HEAD~1..HEAD',
      ],
      { cwd: root, env: { ...env, GIT_DIR: '/nonexistent' }, stderr: 'pipe' },
    );
    expect(await proc.exited).toBe(1);
    expect(await new Response(proc.stderr).text()).toContain(FORMAT_ERROR);
  });

  it('exits 1 when the range does not resolve', async () => {
    const { root } = repoWith([]);
    const result = await runRange(root, 'nope..HEAD');
    expect(result.code).toBe(1);
    expect(result.stderr).toStartWith(
      'commit-msg: git rev-list nope..HEAD failed:',
    );
  });
});
